#!/usr/bin/env node
/**
 * Write the shared header, footer, results and testimonials components into every
 * page that has their placeholder, between COMPONENT markers.
 *
 *   npm run build:components     (also runs in `npm run build`)
 *
 * Why this exists
 * ---------------
 * js/component-loader.js fetched these after page load, so the HTML a crawler gets had
 * no navigation at all: /disclaimer, /terms-of-service, /attorney-referrals, /es and /ru
 * had no crawlable link pointing at them, and the case results and reviews were
 * invisible to anything that doesn't run JS. The loader now skips the fetch when a
 * placeholder is already filled, and still does everything else (active nav item,
 * i18n, event wiring).
 *
 * Edit components/*.html, then run this. Idempotent: re-running rewrites between the
 * markers and produces no diff.
 *
 * Per page:
 *  - the language switcher's EN/ES/RU options become real links when the page declares
 *    hreflang alternates (otherwise they stay "#" and translate in place);
 *  - on es/ru pages the English header and footer get lang="en".
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://penneylaw.com';

// placeholder id → component file
const COMPONENTS = {
    header: 'components/header.html',
    footer: 'components/footer.html',
    results: 'components/results-showcase.html',
    testimonials: 'components/testimonials.html',
};

const SKIP_DIRS = new Set(['node_modules', 'components', 'lp', 'lp-source', '.git', '.netlify', '.playwright-mcp']);

function pages(dir = ROOT) {
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) return SKIP_DIRS.has(entry.name) ? [] : pages(full);
        return entry.name.endsWith('.html') ? [full] : [];
    });
}

/** { en: '/car-accidents', es: '/es/car-accidents', ... } from the page's own hreflang tags. */
function alternates(html) {
    const out = {};
    for (const m of html.matchAll(/<link rel="alternate" hreflang="([a-z]{2})" href="([^"]+)">/g)) {
        out[m[1]] = m[2].replace(SITE, '') || '/';
    }
    return out;
}

function withLanguageLinks(componentHtml, alts) {
    return componentHtml.replace(
        /<a href="#" class="(language-option(?:-mobile)?)([^"]*)" data-lang="(en|es|ru)"/g,
        (m, cls, rest, lang) => (alts[lang] ? `<a href="${alts[lang]}" class="${cls}${rest}" data-lang="${lang}"` : m)
    );
}

function build() {
    const sources = Object.fromEntries(
        Object.entries(COMPONENTS).map(([id, file]) => [id, fs.readFileSync(path.join(ROOT, file), 'utf8').trim()])
    );
    let changed = 0;

    for (const file of pages()) {
        const html = fs.readFileSync(file, 'utf8');
        const pageLang = (/<html lang="([a-z]{2})/.exec(html) || [])[1] || 'en';
        const alts = alternates(html);
        let out = html;

        for (const [id, source] of Object.entries(sources)) {
            const START = `<!-- COMPONENT:${id} START (generated by scripts/build-components.js from ${COMPONENTS[id]} — do not edit here) -->`;
            const END = `<!-- COMPONENT:${id} END -->`;
            const body = id === 'header' ? withLanguageLinks(source, alts) : source;
            // English chrome on a Spanish/Russian page must be read with an English voice.
            const langAttr = pageLang !== 'en' && (id === 'header' || id === 'footer') ? ' lang="en"' : '';
            const pattern = new RegExp(
                `<div id="${id}-placeholder"(?: lang="en")?>(?:<!-- COMPONENT:${id} START[^>]*-->[\\s\\S]*?<!-- COMPONENT:${id} END -->)?</div>`
            );
            out = out.replace(pattern, () => `<div id="${id}-placeholder"${langAttr}>${START}\n${body}\n${END}</div>`);
        }

        // The header/footer are in the HTML now; preloading them only adds a wasted fetch.
        out = out.replace(/ *<link rel="preload" href="\/components\/(?:header|footer)\.html" as="fetch">\n/g, '');
        // Same-origin fetch() is CORS-mode, so the preload must say so or it's never reused.
        out = out.replace('<link rel="preload" href="/config/page-config.json" as="fetch">',
            '<link rel="preload" href="/config/page-config.json" as="fetch" crossorigin>');

        if (out !== html) {
            fs.writeFileSync(file, out);
            changed++;
        }
    }
    console.log(`components: ${changed} page(s) updated`);
}

build();
