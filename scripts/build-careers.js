#!/usr/bin/env node
/**
 * Job postings: careers/jobs.json -> careers/{slug}/index.html, plus the job list on
 * careers/index.html (between the JOBS markers).
 *
 *   npm run build:careers     (also runs in `npm run build`, before build:components,
 *                              which fills the header/footer placeholders it leaves)
 *
 * Why static pages: Indeed crawls career sites, and since 2026-03 it no longer gives
 * free visibility to XML feeds that aren't tied to an ATS. So each job needs its own URL
 * whose HTML (not JS) carries the full posting plus JobPosting JSON-LD, which Google for
 * Jobs reads too. The JSON-LD description is built from the same data as the visible
 * body, so the two can't disagree.
 *
 * To close a job, delete its entry: its folder is removed and the URL 404s, which is
 * what Google asks for once a job is filled. Every folder under careers/ is generated
 * by this script; anything there that isn't a slug in jobs.json gets deleted.
 */

