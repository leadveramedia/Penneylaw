function listingHtml(jobs) {
    if (!jobs.length) {
        return `<p class="job-list-empty">We don&rsquo;t have any open positions right now. We&rsquo;re always glad to hear from people who want to fight for injured Californians &mdash; email your resume to <a href="mailto:${APPLY_EMAIL}">${APPLY_EMAIL}</a>.</p>`;
    }
    return jobs.map((job) => `<article class="job-card">
    <div>
        <h3><a href="/careers/${job.slug}/">${escapeHtml(job.title)}</a></h3>
        ${facts(job, ' job-facts-light')}
        <p class="job-card-pay">${payAmount(job)} <span>${escapeHtml(payNote(job))}</span></p>
        <p>${escapeHtml(job.summary)}</p>
    </div>
    <a class="btn btn-primary" href="/careers/${job.slug}/">View job &amp; apply</a>
</article>`).join('\n');
}

function build() {
    const jobs = JSON.parse(fs.readFileSync(path.join(DIR, 'jobs.json'), 'utf8'));
    const slugs = new Set();
    for (const job of jobs) {
        if (slugs.has(job.slug)) throw new Error(`careers/jobs.json: duplicate slug ${job.slug}`);
        slugs.add(job.slug);
        fs.mkdirSync(path.join(DIR, job.slug), { recursive: true });
        fs.writeFileSync(path.join(DIR, job.slug, 'index.html'), renderJob(job));
    }
    for (const entry of fs.readdirSync(DIR, { withFileTypes: true })) {
        if (entry.isDirectory() && !slugs.has(entry.name)) {
            fs.rmSync(path.join(DIR, entry.name), { recursive: true });
            console.log(`careers: removed closed job ${entry.name}`);
        }
    }

    const indexFile = path.join(DIR, 'index.html');
    const index = fs.readFileSync(indexFile, 'utf8');
    const a = index.indexOf(START);
    const b = index.indexOf(END);
    if (a < 0 || b < a) throw new Error('careers/index.html: JOBS markers missing');
    fs.writeFileSync(indexFile, index.slice(0, a + START.length) + '\n' + listingHtml(jobs) + '\n' + index.slice(b));
    console.log(`careers: ${jobs.length} job page(s) written`);
}

module.exports = { renderJob };

if (require.main === module) build();
