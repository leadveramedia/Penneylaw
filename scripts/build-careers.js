// Google's employmentType values -> what the page shows.
const EMPLOYMENT_TYPES = { FULL_TIME: 'Full-time', PART_TIME: 'Part-time', CONTRACTOR: 'Contract', TEMPORARY: 'Temporary', INTERN: 'Internship' };
const PAY_UNITS = { YEAR: 'year', HOUR: 'hour' };

const escapeHtml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// Escape first, then allow exactly one piece of markup: **bold**.
const inline = (s) => escapeHtml(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
// JSON inside <script>: "<" escaped so no string can close the tag.
const jsonLd = (obj) => `<script type="application/ld+json">${JSON.stringify(obj).replace(/</g, '\\u003c')}</script>`;
const money = (n) => `$${n.toLocaleString('en-US')}`;

function validate(job) {
    const fail = (msg) => { throw new Error(`careers/jobs.json: ${job.slug || '(no slug)'}: ${msg}`); };
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(job.slug || '')) fail('slug must be lowercase words joined by hyphens');
    for (const key of ['title', 'summary']) if (!job[key]) fail(`missing ${key}`);
    if (!OFFICES[job.office]) fail(`office must be one of ${Object.keys(OFFICES).join(', ')}`);
    if (!EMPLOYMENT_TYPES[job.employmentType]) fail(`employmentType must be one of ${Object.keys(EMPLOYMENT_TYPES).join(', ')}`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(job.datePosted || '')) fail('datePosted must be YYYY-MM-DD');
    if (job.validThrough && !/^\d{4}-\d{2}-\d{2}$/.test(job.validThrough)) fail('validThrough must be YYYY-MM-DD');
    // California Labor Code 432.3: every posting needs a pay range (employers with 15+ employees).
    const s = job.salary;
    if (!s || !(s.min > 0) || !(s.max >= s.min) || !PAY_UNITS[s.unit]) fail('salary needs min, max (>= min) and unit YEAR or HOUR');
    if (!Array.isArray(job.intro) || !job.intro.length) fail('intro needs at least one paragraph');
    if (!Array.isArray(job.sections) || !job.sections.every((sec) => sec.heading && Array.isArray(sec.items) && sec.items.length)) {
        fail('every section needs a heading and at least one item');
    }
    for (const sec of job.sections) {
        if (sec.layout && !LAYOUTS.includes(sec.layout)) fail(`section layout must be one of ${LAYOUTS.join(', ')} (or omitted for a checklist)`);
    }
}

// How a section renders on the page. Omitted = checklist beside the summary card;
// "cards" = numbered cards (an item's **bold lead** becomes the card title);
// "tiles" = pay/benefit tiles, the first one featured. The page groups sections by
// layout in that order; the JSON-LD description keeps jobs.json order.
const LAYOUTS = ['cards', 'tiles'];

const office = (job) => OFFICES[job.office];
const url = (job) => `${SITE}/careers/${job.slug}/`;
const payAmount = (job) => `${money(job.salary.min)}–${money(job.salary.max)}`;
const payNote = (job) => `per ${PAY_UNITS[job.salary.unit]}${job.salary.note ? `, ${job.salary.note}` : ''}`;
const posted = (job) => new Date(`${job.datePosted}T00:00:00Z`).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
const icon = (id) => `<svg aria-hidden="true"><use href="/images/icons.svg#icon-${id}"></use></svg>`;
const facts = (job, cls = '') => `<ul class="job-facts${cls}">
    <li>${icon('location')}${escapeHtml(office(job).city)}, CA</li>
    <li>${job.remote ? `${icon('device')}Remote` : `${icon('users')}On-site`}</li>
    <li>${icon('clock')}${EMPLOYMENT_TYPES[job.employmentType]}</li>
</ul>`;
// "**Lead:** rest" -> { lead: 'Lead', rest: 'Rest' }; trailing . or : dropped from the lead,
// and the rest capitalized since it now starts its own line under a heading.
function splitLead(item) {
    const m = /^\*\*(.+?)[.:]?\*\*\s*(.*)$/.exec(item);
    if (!m) return { lead: '', rest: item };
    return { lead: m[1], rest: m[2].charAt(0).toUpperCase() + m[2].slice(1) };
}
const applyHref = (job) => `mailto:${APPLY_EMAIL}?subject=${encodeURIComponent(`Application: ${job.title}`)}`;
const applyText = (job) => `${job.closing ? `${inline(job.closing)} ` : ''}Email your resume to <a href="${applyHref(job)}">${APPLY_EMAIL}</a> with &ldquo;Application: ${escapeHtml(job.title)}&rdquo; in the subject line.`;

function bodyHtml(job) {
    return [
        ...job.intro.map((p) => `<p>${inline(p)}</p>`),
        ...job.sections.map((sec) => `<h2>${escapeHtml(sec.heading)}</h2>\n<ul>\n${sec.items.map((i) => `<li>${inline(i)}</li>`).join('\n')}\n</ul>`),
    ].join('\n');
}

function jobPosting(job) {
    const o = office(job);
    return {
        '@context': 'https://schema.org',
        '@type': 'JobPosting',
        title: job.title,
        description: `${bodyHtml(job)}\n<h2>How to apply</h2>\n<p>${applyText(job)}</p>\n<p>${escapeHtml(EEO)}</p>`,
        datePosted: job.datePosted,
        ...(job.validThrough ? { validThrough: job.validThrough } : {}),
        employmentType: job.employmentType,
        hiringOrganization: { '@type': 'Organization', name: FIRM, sameAs: `${SITE}/`, logo: LOGO },
        jobLocation: {
            '@type': 'Place',
            address: { '@type': 'PostalAddress', streetAddress: o.street, addressLocality: o.city, addressRegion: 'CA', postalCode: o.zip, addressCountry: 'US' },
        },
        // Google requires applicantLocationRequirements whenever jobLocationType is TELECOMMUTE.
        ...(job.remote ? { jobLocationType: 'TELECOMMUTE', applicantLocationRequirements: { '@type': 'Country', name: 'US' } } : {}),
        baseSalary: {
            '@type': 'MonetaryAmount',
            currency: 'USD',
            value: { '@type': 'QuantitativeValue', minValue: job.salary.min, maxValue: job.salary.max, unitText: job.salary.unit },
        },
        directApply: false,
        url: url(job),
    };
}

