#!/usr/bin/env node
/**
 * Inject a crawlable archive of every CMS post into the pages that should link to them.
 *
 *   npm run build:archives     (runs after generate:sitemap in `npm run build`)
 *
 * Why this exists
 * ---------------
 * The blog / accident-news listing pages render their post grid entirely in JS from
 * Storyblok, and pagination is JS state (blog.js reads data-page and re-renders) rather
 * than real URLs. So a crawler saw 2 anchors on blog.html and no path to any of the 122
 * CMS posts — Ahrefs reported all of them as orphans reachable only via sitemap.xml,
 * which means they accumulated no internal PageRank.
 *
 * City posts are a separate case: their /{city}/ hub could never render (Netlify
 * pretty-URL-strips /{city}/ to /{city} because {city}.html exists), so city-listing.html
 * was deleted and city articles now surface on the static location page instead.
 *
 * The block is a visible <details> disclosure, deliberately NOT sr-only: 120+ links
 * hidden from sighted users is a hidden-links pattern we don't want on a law firm site.
 * Crawlers read and follow links inside a closed <details>.
 *
 * Idempotent: rewrites between the ARCHIVE markers when they exist, otherwise inserts
 * before #cta-placeholder. Running the build twice produces no diff.
 *
 * The blog and accident-news listings also get their first page of cards written into
 * the grid (FIRSTPAGE markers). Those cards used to appear only after blog.js and a
 * Storyblok round-trip, so /blog's LCP image (the first card) measured 7.5s on mobile.
 * The browser now only fetches to build pagination, and re-renders on search/tag/page.
 */

const fs = require('fs');
const path = require('path');

const { fetchStoriesFromFolder, CITY_SLUGS } = require('./generate-sitemap.js');

const ROOT = path.join(__dirname, '..');

const START = '<!-- ARCHIVE:START (generated by scripts/build-archives.js — do not edit by hand) -->';
const END = '<!-- ARCHIVE:END -->';
// Preferred insertion point, then a fallback: oakland.html and redding.html render no
// CTA section at all, so they have no #cta-placeholder. Both fall back to </main>, which
// keeps the block inside the main landmark either way.
const ANCHORS = ['<div id="cta-placeholder"></div>', '</main>'];

// City display names, for the region label and summary text.
const CITY_NAMES = {
    sacramento: 'Sacramento',
    roseville: 'Roseville',
    stockton: 'Stockton',
    modesto: 'Modesto',
    oakland: 'Oakland',
    redding: 'Redding',
    chico: 'Chico',
    fairfield: 'Fairfield',
};

function escapeHtml(str) {
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

/** Targets: [file, storyblok folder, url prefix, region label, noun] */
function buildTargets() {
    const targets = [
        ['blog.html', 'blog/', '/blog/', 'Article archive', 'articles'],
        ['accident-news.html', 'accident-news/', '/accident-news/', 'Accident news archive', 'accident news articles'],
    ];
    for (const slug of CITY_SLUGS) {
        const name = CITY_NAMES[slug] || slug;
        targets.push([`${slug}.html`, `${slug}/`, `/${slug}/`, `${name} article archive`, `${name} articles`]);
    }
    return targets;
}

// Listings whose page 1 is prerendered: file → [grid id, loading id, card renderer].
// Same sort and page size as fetchStories() in js/blog.js and js/accident-news.js.
const POSTS_PER_PAGE = 9;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'];

function plainText(node) {
    if (!node) return '';
    if (node.type === 'text') return node.text || '';
    return (node.content || []).map(plainText).join(' ');
}

function cardDate(value) {
    const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(value || ''));
    return m ? { iso: m[0], label: `${MONTHS[Number(m[2]) - 1]} ${Number(m[3])}, ${m[1]}` } : { iso: '', label: '' };
}

/**
 * Mirrors renderBlogCard (js/blog.js) / renderNewsCard (js/accident-news.js) so the
 * browser's own re-renders look identical. Change all three together.
 */
function renderCard(story, urlPrefix, isNews, eager) {
    const c = story.content || {};
    const words = plainText(c.Body_Content).split(/\s+/).filter(Boolean).length;
    const readTime = Math.max(1, Math.ceil(words / 200));
    const image = c.Featured_Image && c.Featured_Image.filename
        ? c.Featured_Image.filename + '/m/600x400'
        : '/images/favicon/social-preview-2026-1200x630.png';
    const alt = (!isNews && c.featured_image_alt) || c.title || '';
    let excerpt = c.excerpt || '';
    if (isNews) {
        const body = plainText(c.Body_Content);
        excerpt = (c.Subheadline && c.Subheadline.trim()) || (body.substring(0, 160).trim() + (body.length > 160 ? '...' : ''));
    }
    const categories = isNews ? [] : (c.categories || []).filter((x) => x && x.trim());
    const date = cardDate(c.Date);
    // The first card is the page's LCP element: load it now, not lazily.
    const loading = eager ? 'loading="eager" fetchpriority="high"' : 'loading="lazy"';
    return `<a href="${urlPrefix}${escapeHtml(story.slug)}" class="card blog-card" aria-label="${escapeHtml(c.title)}">` +
        '<div class="card-image">' +
            `<img src="${escapeHtml(image)}" alt="${escapeHtml(alt)}" width="600" height="400" ${loading}>` +
        '</div>' +
        '<div class="blog-card-body">' +
            '<div class="blog-card-meta">' +
                `<time datetime="${date.iso}">${date.label}</time>` +
                `<span class="blog-card-read-time">${readTime} min read</span>` +
            '</div>' +
            (categories.length ? '<div class="blog-card-categories">' +
                categories.map((x) => `<span class="blog-card-category">${escapeHtml(x)}</span>`).join('') + '</div>' : '') +
            `<h3 class="blog-card-title">${escapeHtml(c.title)}</h3>` +
            `<p class="blog-card-excerpt">${escapeHtml(excerpt)}</p>` +
            '<span class="blog-card-read-more">Read Article</span>' +
        '</div>' +
    '</a>';
}

const FIRST_PAGE = {
    'blog.html': { grid: 'blog-posts-grid', loading: 'blog-loading', news: false },
    'accident-news.html': { grid: 'accident-news-posts-grid', loading: 'accident-news-loading', news: true },
};

function applyFirstPage(html, file, stories, urlPrefix) {
    const cfg = FIRST_PAGE[file];
    const sorted = stories.slice().sort((a, b) =>
        String((b.content && b.content.Date) || '').localeCompare(String((a.content && a.content.Date) || '')));
    const cards = sorted.slice(0, POSTS_PER_PAGE).map((st, i) => renderCard(st, urlPrefix, cfg.news, i === 0)).join('');
    let out = html.replace(
        new RegExp(`<div id="${cfg.grid}" class="grid grid-3 blog-grid" aria-live="polite"[^>]*>(?:<!-- FIRSTPAGE:START -->[\\s\\S]*?<!-- FIRSTPAGE:END -->)?</div>`),
        () => `<div id="${cfg.grid}" class="grid grid-3 blog-grid" aria-live="polite" data-prerendered><!-- FIRSTPAGE:START -->${cards}<!-- FIRSTPAGE:END --></div>`
    );
    // Skeleton starts hidden; blog.js shows it again for searches and page changes.
    out = out.replace(
        new RegExp(`<div id="${cfg.loading}" class="grid grid-3 blog-grid" aria-live="polite"(?: style="display:none;")?>`),
        `<div id="${cfg.loading}" class="grid grid-3 blog-grid" aria-live="polite" style="display:none;">`
    );
    return out;
}

function renderBlock(posts, urlPrefix, label, noun) {
    const items = posts
        .map((p) => {
            const href = urlPrefix + p.slug;
            return `                <li><a href="${href}">${escapeHtml(p.title)}</a></li>`;
        })
        .join('\n');

    const count = posts.length;
    const summary = count === 1
        ? `Browse the ${noun.replace(/s$/, '')}`
        : `Browse all ${count} ${noun}`;

    return [
        START,
        `<section class="section post-archive" aria-label="${escapeHtml(label)}">`,
        '    <div class="container">',
        '        <details class="post-archive-details">',
        `            <summary class="post-archive-summary">${escapeHtml(summary)}</summary>`,
        '            <ul class="post-archive-list">',
        items,
        '            </ul>',
        '        </details>',
        '    </div>',
        '</section>',
        END,
    ].join('\n');
}

/** Replace between markers, else insert before #cta-placeholder. */
function applyBlock(html, block, file) {
    const s = html.indexOf(START);
    const e = html.indexOf(END);
    if (s !== -1 && e !== -1) {
        return html.slice(0, s) + block + html.slice(e + END.length);
    }
    if (s !== -1 || e !== -1) {
        throw new Error(`${file}: found only one ARCHIVE marker — refusing to guess`);
    }
    for (const anchor of ANCHORS) {
        const at = html.indexOf(anchor);
        if (at !== -1) {
            return html.slice(0, at) + block + '\n\n' + html.slice(at);
        }
    }
    throw new Error(`${file}: no insertion anchor found (tried ${ANCHORS.join(', ')})`);
}

/**
 * Remove an existing block entirely (used when a folder has no posts).
 *
 * Strips only the separator this script inserted after the block. A global
 * newline-collapse here would also normalise unrelated blank lines elsewhere in the
 * file, which showed up as phantom diff noise on pages that never had a block.
 */
function stripBlock(html) {
    const s = html.indexOf(START);
    const e = html.indexOf(END);
    if (s === -1 || e === -1) return html;
    let after = e + END.length;
    if (html.startsWith('\n\n', after)) after += 2;
    return html.slice(0, s) + html.slice(after);
}

(async () => {
    let injected = 0;
    let skipped = 0;
    let totalLinks = 0;

    for (const [file, folder, urlPrefix, label, noun] of buildTargets()) {
        const full = path.join(ROOT, file);
        if (!fs.existsSync(full)) {
            console.warn(`  ${file}: missing — skipped`);
            continue;
        }

        // Sorted by title so the output is deterministic: publish-date order would
        // reshuffle the block on unrelated CMS edits and churn the committed diff.
        let stories;
        try {
            stories = await fetchStoriesFromFolder(folder, { mapStory: (s) => s });
        } catch (err) {
            // Storyblok failed: leave the committed block alone rather than stripping
            // every archive link from the deploy.
            console.warn(`::warning::${file}: ${err.message} — keeping the existing archive block`);
            skipped++;
            continue;
        }
        const posts = stories.map((s) => ({
            slug: s.slug,
            title: String((s.content && s.content.title) || s.name || s.slug).trim(),
        })).sort((a, b) => a.title.localeCompare(b.title));

        let html = fs.readFileSync(full, 'utf8');
        if (FIRST_PAGE[file] && stories.length) {
            const withCards = applyFirstPage(html, file, stories, urlPrefix);
            if (withCards !== html) fs.writeFileSync(full, withCards);
            html = withCards;
        }

        if (posts.length === 0) {
            // No posts: make sure a stale block from a previous build doesn't linger.
            const out = stripBlock(html);
            if (out !== html) {
                fs.writeFileSync(full, out);
                console.log(`  ${file}: 0 posts — removed stale archive block`);
            } else {
                console.log(`  ${file}: 0 posts — no block`);
            }
            skipped++;
            continue;
        }

        const out = applyBlock(html, renderBlock(posts, urlPrefix, label, noun), file);
        if (out !== html) fs.writeFileSync(full, out);
        console.log(`  ${file}: ${posts.length} links`);
        injected++;
        totalLinks += posts.length;
    }

    console.log(`\narchives: ${injected} pages injected, ${skipped} skipped, ${totalLinks} internal links total`);
})().catch((err) => {
    console.error('Archive generation failed:', err.message);
    process.exit(1);
});
